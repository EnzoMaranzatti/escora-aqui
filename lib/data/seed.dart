/// Fictional points for the demo (the briefing asks for fake data). Dates
/// are relative to today so the demo never goes stale.
DateTime _in(int days, [int hour = 0]) {
  final n = DateTime.now();
  return DateTime(n.year, n.month, n.day + days, hour);
}

DateTime _ago(int days) => _in(-days, 10);

/// Next [weekday] (1 = segunda) at least one day ahead.
DateTime _next(int weekday) {
  var d = _in(1);
  while (d.weekday != weekday) {
    d = d.add(const Duration(days: 1));
  }
  return d;
}

LatLng _offset(LatLng c, double east, double north) {
  const kmPerLat = 110.574;
  final kmPerLng = 111.320 * math.cos(c.latitude * math.pi / 180);
  return LatLng(c.latitude + north / kmPerLat, c.longitude + east / kmPerLng);
}

